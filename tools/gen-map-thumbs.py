"""Make small map pictures for the map pages from the overview layers.

The overview layers are 8192 px webps of about 7 MB each, sized for the replay
viewer's zoom. A map page header only needs a picture a few hundred pixels
wide, so this cuts each map's topmost layer (the one that shows the whole map
from above) down to its content box and writes two small webps per map:

    <out>/<map>.thumb640.webp    for cards and the phone header
    <out>/<map>.thumb1280.webp   for the desktop header

and regenerates src/mapThumbs.ts, the list of maps that have them, so the site
never asks for a picture that does not exist.

The source layer is read from web/public/overviews when the file is there, and
otherwise fetched from the URL src/mapOverviews.ts already serves it from, into
a cache directory so a rerun does not download it again.

Usage:
    python3 tools/gen-map-thumbs.py --cache /tmp/overview-cache \\
        --out web/public/overviews/thumbs

Then upload the thumbs to R2 next to the layers:
    npx tsx scripts/upload-overviews.ts --dir=web/public/overviews/thumbs --upload
"""
import argparse
import os
import re
import urllib.request

from PIL import Image

parser = argparse.ArgumentParser()
parser.add_argument('--overviews', default='src/mapOverviews.ts', help='the generated overview module')
parser.add_argument('--local', default='web/public/overviews', help='where full layers may already be')
parser.add_argument('--cache', required=True, help='where fetched layers are kept between runs')
parser.add_argument('--out', default='web/public/overviews/thumbs', help='where the thumbnails go')
parser.add_argument('--module', default='src/mapThumbs.ts', help='the TypeScript list to write')
args = parser.parse_args()

WIDTHS = (640, 1280)
QUALITY = 72

text = open(args.overviews, encoding='utf-8').read()

# One entry per map: its layers in ascending cut order and its content box.
# The module is generated, so its shape is fixed and a regex is enough.
entries = re.findall(
    r"'([^']+)': \{\s*map: '[^']+',\s*layers: \[(.*?)\],\s*contentBox: \{ x0: (\d+), y0: (\d+), x1: (\d+), y1: (\d+) \}",
    text, re.S)
if not entries:
    raise SystemExit(f'no maps found in {args.overviews}')

os.makedirs(args.cache, exist_ok=True)
os.makedirs(args.out, exist_ok=True)

made = {}
for name, layers, x0, y0, x1, y1 in entries:
    urls = re.findall(r"image: '([^']+)'.*?width: (\d+), height: (\d+)", layers)
    if not urls:
        continue
    url, lw, lh = urls[-1]  # the highest cut shows the whole map
    file = url.rsplit('/', 1)[-1]
    path = os.path.join(args.local, file)
    if not os.path.exists(path):
        path = os.path.join(args.cache, file)
        if not os.path.exists(path):
            print(f'fetch {file}')
            urllib.request.urlretrieve(url, path)
    img = Image.open(path).convert('RGB')
    # The content box is in the layer's own pixel space; a layer on disk at
    # another size is scaled into it so the crop still lands on the map.
    sx, sy = img.width / int(lw), img.height / int(lh)
    box = (int(int(x0) * sx), int(int(y0) * sy), int(int(x1) * sx), int(int(y1) * sy))
    crop = img.crop(box)
    for w in WIDTHS:
        h = max(1, round(crop.height * w / crop.width))
        crop.resize((w, h), Image.LANCZOS).save(os.path.join(args.out, f'{name}.thumb{w}.webp'), 'WEBP', quality=QUALITY, method=6)
    made[name] = (crop.width, crop.height)
    print(f'{name}: {crop.width}x{crop.height}')

base = re.search(r"image: '(.*)/[^/']+'", text).group(1)
lines = [
    '/**',
    ' * Small map pictures for the map pages, generated by tools/gen-map-thumbs.py.',
    ' *',
    ' * Do not edit by hand. A map is listed only when its thumbnails were written,',
    ' * so the site never asks for a picture that does not exist. The value is the',
    ' * aspect ratio (width over height) of the cropped map, so a header can reserve',
    ' * its space before the picture loads.',
    ' *',
    ' * No imports, deliberately: loaded by the browser as well as the server.',
    ' */',
    '',
    "// Uploaded beside the layers (scripts/upload-overviews.ts keys a file as",
    "// overviews/<name>), so they share the layers' base URL.",
    f"export const MAP_THUMB_BASE = '{base}';",
    '',
    'export const MAP_THUMBS: Record<string, number> = {',
]
for name in sorted(made):
    w, h = made[name]
    lines.append(f"  '{name}': {w / h:.4f},")
lines += [
    '};',
    '',
    '/** The thumbnail URL for a map at a width, or null when there is none. */',
    'export function mapThumb(map: string, width: 640 | 1280): string | null {',
    '  return MAP_THUMBS[map] !== undefined ? `${MAP_THUMB_BASE}/${map}.thumb${width}.webp` : null;',
    '}',
    '',
]
open(args.module, 'w', encoding='utf-8').write('\n'.join(lines))
print(f'{len(made)} maps -> {args.module}')
